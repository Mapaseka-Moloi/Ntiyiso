#!/usr/bin/env python3
"""Compose every page of the split site from the extracted markup slices.

The markup in build/extracted/markup/ is verbatim build/monolith.html, so nothing
is retyped: each feature's index.html is the original block(s) wrapped in the
document shell, with navigation turned into real root-absolute links. The page
scripts are written here too, because each one is only a few lines.

Run after tools/extract.py:
    python tools/build_pages.py
"""

import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKUP = os.path.join(ROOT, "build", "extracted", "markup")

BANNER = "<!-- Generated by tools/build_pages.py from build/monolith.html. -->\n"

LOGO = "/assets/logo.png"


# ── helpers ────────────────────────────────────────────────────────────────
def cut(name):
    with io.open(os.path.join(MARKUP, name + ".html"), encoding="utf-8") as fh:
        return fh.read().rstrip("\n")


def write(rel_path, text):
    path = os.path.join(ROOT, rel_path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    body = BANNER + text.lstrip("\n")
    if not body.endswith("\n"):
        body += "\n"
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print("wrote %-38s %6d bytes" % (rel_path, len(body)))


def substitute(text, old, new, count=1):
    if old not in text:
        raise SystemExit("markup target not found:\n" + old[:160])
    return text.replace(old, new, count)


def page(title, description, styles, scripts, body, html_attrs=""):
    """Wrap a body in the shared document shell. All hrefs/srcs are root-absolute."""
    links = "\n".join(
        '<link rel="stylesheet" href="%s" />' % href for href in styles)
    tags = "\n".join('<script src="%s" defer></script>' % src for src in scripts)
    return """<!DOCTYPE html>
<html lang="en-ZA" data-text="large" data-theme="system"%(attrs)s>
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
<meta name="description" content="%(desc)s" />
<meta name="color-scheme" content="light" />
<title>%(title)s</title>
<link rel="icon" href="%(logo)s" />
%(links)s
</head>
<body>
%(body)s
%(scripts)s
</body>
</html>
""" % {"attrs": html_attrs, "desc": description, "title": title,
       "logo": LOGO, "links": links, "body": body, "scripts": tags}


# ── navigation rewrite ─────────────────────────────────────────────────────
def use_logo(text):
    """Swap the inline SVG lockups for the real asset."""
    return re.sub(r'src="data:image/svg\+xml,[^"]*"', 'src="%s"' % LOGO, text)


def tabbar(active):
    """The four bottom tabs are four URLs. Only the one you are on is current.

    The extracted markup hard-codes aria-current on the check tab, because in
    the single-page build that was the default screen. It is stripped here and
    re-applied to whichever tab owns the page being written.
    """
    bar = use_logo(cut("m_cust_tabbar"))
    bar = bar.replace('<button data-go="%s" aria-current="page">' % "check",
                      '<button data-go="check">', 1)
    bar = re.sub(r'<button data-go="([a-z]+)">',
                 lambda m: '<a class="tabbar-link" href="/app/%s"%s>'
                 % (m.group(1),
                    ' aria-current="page"' if m.group(1) == active else ""),
                 bar)
    bar = bar.replace("</button>", "</a>")
    return bar


def appbar():
    bar = use_logo(cut("m_cust_appbar"))
    # Settings is a page, so it is a link. Sign out stays a button - it is an
    # action, not a place.
    bar = substitute(
        bar,
        '<button class="iconbtn" id="custSettings" aria-label="Settings"',
        '<a class="iconbtn" id="custSettings" href="/app/settings" aria-label="Settings"')
    bar = substitute(bar, 'stroke-linecap="round"><circle cx="12" cy="12" r="3.2"/>'
                         '<path d="M12 3v2.2M12 18.8V21M4.2 7.5l1.9 1.1M17.9 15.4l1.9 1.1'
                         'M4.2 16.5l1.9-1.1M17.9 8.6l1.9-1.1"/></svg>\n</button>',
                         'stroke-linecap="round"><circle cx="12" cy="12" r="3.2"/>'
                         '<path d="M12 3v2.2M12 18.8V21M4.2 7.5l1.9 1.1M17.9 15.4l1.9 1.1'
                         'M4.2 16.5l1.9-1.1M17.9 8.6l1.9-1.1"/></svg>\n</a>')
    return bar


RAIL_LINKS = [
    ("home", "Overview", None),
    ("live", "Live cockpit", "01"),
    ("queue", "Threat radar", "02"),
    ("business", "Business case", "03"),
    ("case", "Case study", "04"),
]
RAIL_PATHS = {"home": "/desk/overview", "live": "/desk/live", "queue": "/desk/radar",
              "business": "/desk/business", "case": "/desk/case"}


def rail(active):
    """The left rail is five links to five URLs, with one marked as current."""
    out = ['<aside class="rail">', '<nav id="navTabs" aria-label="Desk sections">']
    for view, label, num in RAIL_LINKS:
        current = ' aria-current="page"' if view == active else ""
        icon = (cut_icon(view))
        out.append('<a data-view="%s" href="%s"%s>' % (view, RAIL_PATHS[view], current))
        out.append('  <span class="n">%s</span>' % icon)
        if view == "queue":
            out.append('  <span class="t">Threat radar'
                       '<span class="rbadge" id="threatCount">2</span></span>')
        else:
            out.append('  <span class="t">%s</span>' % label)
        out.append('</a>')
    out.append('</nav>')
    tail = cut("m_desk_rail").split("</nav>", 1)[1].rstrip("\n")
    return "\n".join(out) + "\n" + tail


def cut_icon(view):
    if view != "home":
        return RAIL_LINKS[[r[0] for r in RAIL_LINKS].index(view)][2]
    return ('<svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor"'
            ' stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">'
            '<path d="M3 10.5 12 3l9 7.5"/><path d="M5 9.5V21h14V9.5"/></svg>')


def view(name):
    """One view per document, so it is always the one showing."""
    return use_logo(cut("m_view_" + name)).replace(
        '<section id="view-%s" class="view">' % name,
        '<section id="view-%s" class="view on">' % name, 1)


def desk_chrome(active, body):
    return "\n".join([
        cut("m_grain"),
        use_logo(cut("m_desk_header")),
        cut("m_shell_open"),
        body,
        cut("m_main_close"),
        rail(active),
        cut("m_shell_close"),
        cut("m_desk_footer"),
        cut("m_liveness_modal"),
        # Closed here, not in the slice: the source is one </div> short of
        # closing #settingsModal, and without this the toast host ends up
        # nested inside the modal, which is display:none by default.
        cut("m_settings_modal"),
        "</div><!-- /#settingsModal -->",
        cut("m_desk_toasts"),
    ])


