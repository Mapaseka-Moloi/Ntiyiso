# ── customer auth pages ────────────────────────────────────────────────────
AUTH_TABS = """<div class="tabs" id="authTabs" aria-label="Sign in or create an account">
<a href="/auth/login"%(here)s>Sign in</a>
<a href="/auth/signup"%(there)s>Create account</a>
</div>"""


def auth_head():
    """The auth hero: the logo, plus the wordmark the old lockup carried.

    `m_auth_head` pointed at a 340x100 inline SVG whose art was the shield plus
    the words "mukuru NTIYISO". assets/logo.png is the shield alone, so without
    this the sign-in screen shows a bare mark with no product name on it.
    """
    head = use_logo(cut("m_auth_head"))
    head = substitute(
        head, 'alt="mukurú NTIYISO" />',
        'alt="" />\n<p class="wordmark">mukurú <b>NTIYISO</b></p>')
    return head


def auth_body(mode):
    form = cut("m_auth_signin") if mode == "signin" else cut("m_auth_signup")
    # The active mode is this page; the other one is a link.
    tabs = AUTH_TABS % {"here": ' aria-current="page"' if mode == "signin" else "",
                        "there": ' aria-current="page"' if mode == "signup" else ""}
    title = "Sign in · Ntiyiso" if mode == "signin" else "Create an account · Ntiyiso"
    label = "Sign in to Ntiyiso" if mode == "signin" else "Create your Ntiyiso account"
    return title, "\n".join([
        '<div class="auth">',
        '<div class="auth-inner">',
        auth_head(),
        cut("m_auth_step1"),
        '<div id="authStep2" class="hidden">',
        cut("m_auth_step2"),
        tabs,
        cut("m_auth_note"),
        form,
        cut("m_auth_social"),
        "</div>",
        "</div>",
        "</div>",
    ]), label


def build_auth_pages():
    for mode in ("signin", "signup"):
        name = "login" if mode == "signin" else "signup"
        title, body, label = auth_body(mode)
        write("auth/%s/index.html" % name, page(
            title=title,
            description="Sign in to Ntiyiso, or create an account. Prototype: "
                        "accounts are stored on this device only.",
            styles=["/shared/css/base.css", "/shared/css/customer.css",
                    "/shared/css/auth.css", "/auth/%s/styles.css" % name],
            scripts=["/shared/js/customer.js", "/auth/%s/script.js" % name],
            body=body,
        ))
        write("auth/%s/script.js" % name, """/* /auth/%s - %s
 * Role picker, credentials and the provider buttons, all shared. The only
 * difference between the two auth pages is which form is on the document.
 */
(function(){
var C = window.NT.cust;
C.loadState();
C.loadAlerts();
C.applyDocument();
/* Already signed in? Go straight to wherever that role belongs, so the login
   screen is never a dead end. */
if(C.session()){ C.enterApp(); return; }
C.wireAuthShell('%s');
})();
""" % (name, label.lower(), mode))


